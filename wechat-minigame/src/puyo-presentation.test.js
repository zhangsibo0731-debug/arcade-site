'use strict';

const assert = require('assert');
global.window = global;
require('../vendor/puyo/challenge-rules.js');
require('../vendor/puyo/roguelite-rules.js');
const p = require('./puyo-presentation.js');
const game = { rules: window.PuyoChallengeRules, rogue: window.PuyoRogueliteRules, mode: 'playing', turnStats: {} };
game.challenge = game.rules.normalize({ stage: 8 });
game.build = game.rogue.normalize({ upgrades: { chainShield: 2, palette: 1 }, relics: ['echoBottle'] }, 0);
game.challenge.mission = { type: 'targetColor', color: 1, target: 6, progress: 1, title: '累计消除 6 颗红色噗呦' };
game.challenge.deferredGarbage = 123;
game.challenge.deferredIn = 2;
game.challenge.pendingGarbage = 5;
game.challenge.pressureIn = 8;
let task = p.mission(game);
assert.strictEqual(task.scope, '累计任务');
assert.strictEqual(task.garbage, '待落 ×99+');
assert.strictEqual(task.eta, '近期 · 2 组后落下');
assert.strictEqual(task.later, '后续 ×5 · 8 组后');
assert.strictEqual(task.imminent, true);
game.mode = 'resolving';
game.turnStats = { missionBaseProgress: 1, colorClearedCount: 2 };
task = p.mission(game);
assert.strictEqual(task.progress, '已累计消除 3 / 6 颗');
assert.strictEqual(task.ratio, .5);
game.mode = 'mission';
assert.strictEqual(p.mission(game).progress, task.progress, 'opening task details preserves the in-flight progress preview');
game.turnStats = {};
game.challenge.deferredGarbage = 0;
game.challenge.pendingGarbage = 0;
assert.strictEqual(p.mission(game).eta, '暂无待落干扰');
game.challenge.special = { type: 'tower', title: '高塔危机' };
game.build.contract = { stage: game.challenge.stage, status: 'active' };
assert.strictEqual(p.mission(game).special, '高塔危机');
assert.ok(p.mission(game).contract.includes('额外'));
game.choiceKind = 'upgrade';
game.build.pendingKind = 'contract';
game.build.pendingChoice = ['chainShield', 'cohesion'];
const cards = p.choiceCards(game);
assert.strictEqual(p.rewardTitle(game), '契约奖励 · 额外强化');
assert.strictEqual(cards[0].levelText, '升级至 3 级');
assert.ok(cards[0].synergyText.includes('已联动'));
assert.ok(p.buildCards(game).some((entry) => entry.title.includes('连锁护盾 · 2 级') && entry.effect === game.rogue.BY_ID.chainShield.effects[1]), 'owned capabilities show their current effect, not the next upgrade');
assert.ok(p.buildCards(game).some((entry) => entry.title.includes('回声瓶')));
const rows = p.resultRows({ gameType: 'challenge', score: 1200, level: 4, maxChain: 3, bestChain: 8, cleared: 90, allClearCount: 2, challenge: { completed: 6, garbageCleared: 14 } });
assert.deepStrictEqual(rows.find((entry) => entry[0] === '历史最高连锁'), ['历史最高连锁', 8]);
assert.strictEqual(rows.length, 8);
console.log('wechat presentation models tests passed');
