'use strict';

const assert = require('assert');
global.window = global;
require('../vendor/puyo/storage.js');
const saveModule = require('./puyo-save.js');
const values = new Map();
const storage = { get: (key, fallback) => values.has(key) ? values.get(key) : fallback, set: (key, value) => { values.set(key, value); return true; }, remove: (key) => values.delete(key) };
const validators = window.PuyoStorage.create({ rows: 12, cols: 6, maxCell: 8, colorCount: 5, rotationCount: 4 });
const saves = saveModule.create(storage, validators);
const board = Array.from({ length: 12 }, () => Array(6).fill(0));
const legacy = { version: 2, gameType: 'challenge', board, score: 800, cleared: 24, maxChain: 3, activeMs: 9000, challenge: { stage: 4 }, build: { upgrades: { foresight: 2 } } };
values.set(saveModule.LEGACY_KEY, legacy);
const converted = saves.load();
assert.strictEqual(converted.gameType, 'challenge');
assert.strictEqual(converted.clearedTotal, 24);
assert.strictEqual(converted.runMaxChain, 3);
assert.strictEqual(converted.activeDurationMs, 9000);
assert.strictEqual(converted.challengeState.stage, 4);
assert.strictEqual(converted.runBuild.upgrades.foresight, 2);
assert.strictEqual(values.get(saveModule.LEGACY_KEY), legacy, 'migration preserves the original save');
assert.ok(saves.save(converted));
saves.save({ ...converted, gameType: 'classic', score: 42 });
assert.strictEqual(saves.load().gameType, 'classic');
assert.strictEqual(values.get(saveModule.keyFor('challenge')).score, 800);
saves.clear('classic');
assert.strictEqual(saves.load(), null, 'finishing a run cannot resurrect an older mode or v2 save');
assert.strictEqual(saves.convert({ gameType: 'challenge', board: [[1]] }), null);
const badClassic = board.map((row) => row.slice()); badClassic[11][0] = 6;
assert.strictEqual(saves.convert({ gameType: 'classic', board: badClassic }), null);
const failing = saveModule.create({ ...storage, set: () => false }, validators);
assert.strictEqual(failing.save(converted), false, 'a failed write must not report a successful migration');
console.log('wechat save migration tests passed');
